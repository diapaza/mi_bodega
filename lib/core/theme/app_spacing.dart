/// Escala de espaciado consistente para MiBodega.
abstract class AppSpacing {
  /// 4px - espacio mínimo (badges, gaps internos)
  static const double xs = 4;

  /// 8px - espacio pequeño (entre elementos inline, separadores)
  static const double sm = 8;

  /// 12px - espacio medio (campos de formulario, gaps entre cards)
  static const double md = 12;

  /// 16px - espacio estándar (padding de página, gaps grandes)
  static const double lg = 16;

  /// 24px - espacio grande (secciones, entre secciones)
  static const double xl = 24;

  /// 32px - espacio muy grande (separación entre bloques principales)
  static const double xxl = 32;

  /// 40px - espacio extra grande (márgenes de空��态)
  static const double xxxl = 40;
}
